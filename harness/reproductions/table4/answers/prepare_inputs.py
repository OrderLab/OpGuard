"""Maintainer-only assembly of solver inputs and separate answer provenance."""
import argparse
import json
from pathlib import Path
import secrets
import shutil
import tempfile

import torch
from opguard_harness.input_bundle import export_inputs, sha256, verify_inputs
from prepare_cases import extract


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("study", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--private-output", type=Path, required=True)
    args = parser.parse_args()
    study, output, private = (p.resolve() for p in (args.study, args.output, args.private_output))
    if output == private or output in private.parents or private in output.parents:
        parser.error("Input and private output directories must not overlap")
    if output.exists() or private.exists():
        parser.error("Use new output directories; historical inputs are immutable")
    repo = Path(__file__).resolve().parents[3]
    if repo == output or repo in output.parents or study == output or study in output.parents:
        parser.error("Export outside the maintainer checkout and historical study")
    templates = repo / "reproductions/table4/inputs"
    files, origins, cases = {}, {}, {}

    def add(source, target):
        if target in files:
            raise ValueError(f"Duplicate destination: {target}")
        files[target] = source
        origins[target] = str(source)

    def tree(source, target, suffixes):
        for path in sorted(source.rglob("*")):
            if path.is_file() and path.suffix in suffixes and not any(
                    part.startswith(".") or part == "__pycache__" for part in path.relative_to(source).parts):
                add(path, f"{target}/{path.relative_to(source).as_posix()}")

    with tempfile.TemporaryDirectory(prefix="opguard-input-assembly-") as temporary:
        temporary = Path(temporary)

        def generated(target, content):
            path = temporary / target
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            add(path, target)
            origins[target] = "generated by maintainer input preparation"

        add(templates / "README.md", "README.md")
        add(templates / "run_task.py", "run_task.py")
        tree(repo / "skills", "skills", {".md"})
        tree(repo / "opguard_harness", "opguard_harness", {".py"})
        add(repo / "LICENSE", "LICENSE")
        for case in range(21, 29):
            identifier = secrets.token_hex(8)
            task_root = f"tasks/{identifier}"
            cases[str(case)] = {"task": identifier}
            task = {"id": identifier, "comparison": "bitwise", "workloads": {}}
            env = {"OPGUARD_CALLSITE_CUPTI": "0", "OPGUARD_CALLSITE_CUDAAPI": "0",
                   "OPGUARD_CALLSITE_INCLUDE_CPU": "1", "OPGUARD_TRACE_DUMP_MODE": "summary",
                   "CUBLAS_WORKSPACE_CONFIG": ":4096:8", "OMP_NUM_THREADS": "1"}
            ranks = 2 if case in (21, 25) else 4 if case == 24 else 1
            env["CUDA_VISIBLE_DEVICES"] = ",".join(map(str, range(ranks)))
            if case in (21, 25):
                env["CUDA_DEVICE_MAX_CONNECTIONS"] = "8"
            if case == 24:
                env["CUDA_DEVICE_MAX_CONNECTIONS"] = "1"
            native = case in (22, 26)
            task["reference_kind"] = "saved_observation" if native else "executable_configuration"
            task["criterion"] = ("Identical repeated inputs should produce identical outputs; compare the saved reference as well."
                                 if native else "Compare corresponding outputs under the two supplied configurations.")
            for side in (("candidate",) if native else ("baseline", "candidate")):
                target = f"{task_root}/{side}"
                argv = []
                if case in (21, 25):
                    version, stage = ("0.9.5", "2") if case == 21 else ("0.14.2", "1")
                    template = "workload_zero.py"
                    upstream = study / f"vendor/deepspeed-{version}"
                    tree(upstream / "deepspeed", f"{target}/deepspeed", {".py", ".yaml", ".json"})
                    # These upstream package links are materialized from explicit
                    # source directories; no symlink is exported or followed by
                    # the generic bundle writer.
                    for source, destination in (("accelerator", "accelerator"),
                                                ("op_builder", "ops/op_builder"),
                                                ("csrc", "ops/csrc")):
                        tree(upstream / source, f"{target}/deepspeed/{destination}",
                             {".py", ".h", ".hpp", ".cuh", ".cpp", ".cu"})
                    argv = ["--stage", stage, "--steps", "4", "--delay-cycles", "50000000",
                            "--loss-scale", "128", "--weighted", "--output", "observed",
                            "--overlap", "0" if side == "baseline" else "1"]
                elif native:
                    version, build, module = (("0.9.1", "ds091", "ds_inference_091") if case == 22
                                               else ("0.7.0", "ds070", "ds_inference_070"))
                    template = "workload_context.py" if case == 22 else "workload_attention.py"
                    add(study / f"extensions/{build}/{module}.so", f"{target}/native/{module}.so")
                    tree(study / f"vendor/deepspeed-{version}/csrc", f"{target}/source/csrc", {".h", ".hpp", ".cuh", ".cpp", ".cu"})
                    argv = ["--extension", "native", "--output", "observed.pt"]
                    if case == 26:
                        argv += ["--module", module]
                elif case == 23:
                    template = "workload_vocab.py"
                    generated(f"{target}/tokenizer.py", extract(study / "vendor/raw/tokenizer.py",
                              "_vocab_size_with_padding", "import math\n"))
                    argv = ["--tp", "1" if side == "baseline" else "2"]
                elif case == 24:
                    template = "workload_dispatcher.py"
                    tree(study / "vendor/megatron/megatron", f"{target}/megatron", {".py", ".yaml", ".json", ".cu", ".cpp", ".h"})
                    argv = ["--dispatcher", "allgather" if side == "baseline" else "alltoall", "--topk", "3"]
                elif case == 27:
                    template = "workload_vision.py"
                    version = "4.54.1" if side == "baseline" else "4.55.1"
                    generated(f"{target}/modeling_smolvlm.py", extract(study / f"vendor/raw/smolvlm-{version}.py",
                              "SmolVLMVisionEmbeddings", "from __future__ import annotations\nimport torch\nfrom torch import nn\n"))
                else:
                    template = "workload_qwen.py"
                    add(study / "case28/baseline/modeling_qwen2_vl.py", f"{target}/modeling_qwen2_vl.py")
                    argv = ["--mode", "generate" if side == "baseline" else "call"]
                add(templates / template, f"{target}/workload.py")
                task["workloads"][side] = {"script": "workload.py", "args": argv,
                                            "env": env, "ranks": list(range(ranks))}
            if native:
                source = study / ("case22/raw-baseline.pt" if case == 22 else "case26/long-baseline.pt")
                reference = torch.load(source, map_location="cpu", weights_only=True)
                path = temporary / f"{task_root}/reference.pt"
                path.parent.mkdir(parents=True, exist_ok=True)
                torch.save(reference, path)
                add(path, f"{task_root}/reference.pt")
                origins[f"{task_root}/reference.pt"] = str(source)
                cases[str(case)]["reference_source"] = str(source)
                cases[str(case)]["reference_source_sha256"] = sha256(source)
                cases[str(case)]["reference_provenance"] = "Observed output of a known repair control; repaired source and binaries are intentionally withheld. This is not an executable unmodified baseline."
                task["reference"] = "reference.pt"
            generated(f"{task_root}/task.json", json.dumps(task, indent=2) + "\n")
        manifest = export_inputs(output, dict(sorted(files.items())))
        verify_inputs(output)
        private.mkdir(parents=True)
        answer_source = Path(__file__).resolve().parent
        shutil.copytree(answer_source, private / "answers",
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        provenance = {"input_bundle": str(output), "input_manifest_sha256": sha256(output / "manifest.json"),
                      "cases": cases, "origins": origins,
                      "answer_materials": str(private / "answers"),
                      "maintainer_answer_source": str(answer_source),
                      "historical_study": str(study),
                      "evaluation_status": "inputs_prepared; no blind diagnosis has been run"}
        (private / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
        print(json.dumps({"input_bundle": str(output), "private_records": str(private),
                          "tasks": len(cases), "files": len(manifest["files"])}))


if __name__ == "__main__":
    main()
