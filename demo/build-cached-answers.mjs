// Build the browser and Worker copies from the same reviewed answer bank.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url);
const bank=JSON.parse(readFileSync(new URL('demo/answer-bank.json',root),'utf8'));
const sources={};
for(const [file,sha] of Object.entries(bank.source_sha256)){
  const run=/^(run[12])\/deepspeed\/runtime\/zero\/stage_1_and_2\.py$/.exec(file)?.[1];
  assert(run,'Only captured public sources are allowed');
  const bytes=readFileSync(new URL(`demo/sources/${run}-stage_1_and_2.py`,root));
  assert.equal(createHash('sha256').update(bytes).digest('hex'),sha,'Re-review examples when source changes');
  sources[file]=bytes.toString().split(/\r?\n/);
}
for(const check of bank.source_checks)assert(sources[check.file]?.[check.line-1]?.includes(check.contains),JSON.stringify(check));
const checked=new Set(bank.source_checks.map(c=>`${c.file}:${c.line}`));
for(const [arm,answers]of Object.entries(bank.arms)){
  assert(['trace','opguard'].includes(arm));assert(answers.length>1);
  assert.equal(new Set(answers.map(a=>a.id)).size,answers.length);
  for(const answer of answers){
    assert(answer.id&&answer.answer);
    for(const cite of answer.answer.matchAll(/run[12]\/deepspeed\/runtime\/zero\/stage_1_and_2\.py:\d+/g))assert(checked.has(cite[0]),`Unchecked citation: ${cite[0]}`);
  }
}
const data={version:bank.version,notice:bank.notice,provenance:bank.provenance,arms:bank.arms};
const json=JSON.stringify(data).replaceAll('<','\\u003c');
writeFileSync(new URL('js/rootcause-answers.js',root),'// Generated by demo/build-cached-answers.mjs. Reviewed examples; no model calls.\nwindow.OPGUARD_DEMO_ANSWERS = '+json+';\n');
writeFileSync(new URL('demo/cached-answers.js',root),'// Generated by build-cached-answers.mjs.\nexport const cachedAnswers = '+json+';\n');
console.log(`Checked ${bank.source_checks.length} source anchors; built ${Object.values(bank.arms).flat().length} reviewed examples.`);
