import { encode } from 'gpt-tokenizer/encoding/o200k_base';
import { writeFileSync } from 'node:fs';
import { packets } from './packets.js';
const chunks = {};
for (const [arm, packet] of Object.entries(packets)) {
  const pieces = []; let current = '';
  // Preserve every byte and original line order, including long configuration lines.
  for (const line of packet.match(/[^\n]*\n|[^\n]+$/g)) {
    if (encode(current + line).length > 2500 && current) { pieces.push(current); current = ''; }
    if (encode(line).length > 2500) throw new Error('Single line exceeds chunk budget');
    current += line;
  }
  if (current) pieces.push(current);
  if (pieces.join('') !== packet) throw new Error('Input was changed');
  chunks[arm] = pieces.map(text => ({text, tokens: encode(text).length}));
}
writeFileSync(new URL('./chunks.js', import.meta.url), '// Generated by build_chunks.mjs (o200k_base).\nexport const chunks = ' + JSON.stringify(chunks) + ';\n');
console.log(Object.fromEntries(Object.entries(chunks).map(([arm,parts]) => [arm,parts.map(p=>p.tokens)])));
