"""Build fixed inputs from the path-normalized same-launch capture; no answer/source hints."""
import hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
evidence = ROOT / 'demo/evidence'
manifest = json.loads((evidence / 'manifest.json').read_text())
expected = {f['path']: f for f in manifest['files']}
shared = 'Two DeepSpeed training runs, run1 overlap_comm=False and run2 overlap_comm=True, use the same workload. Diagnose their numerical divergence.\n'
parts = [shared, 'Complete standard logs with normalized host paths, in original order within each stream. stdout/stderr were captured separately; their interleaving is unknown.\n']
for side in ('overlap-off', 'overlap-on'):
    for stream in ('stdout', 'stderr'):
        data = (evidence / f'{side}-{stream}.log').read_bytes()
        assert hashlib.sha256(data).hexdigest() == expected[f'standard-logs/{side}/{stream}.log']['sha256']
        parts.append(f'\n--- {side} / {stream} ---\n' + data.decode())
raw = (evidence / 'opguard-output.json').read_bytes()
assert hashlib.sha256(raw).hexdigest() == expected['opguard-output.json']['sha256']
report = json.loads(raw)
compact = {'kind': 'first observed differences at captured callsites', 'ranks': [], 'limits': report['limits']}
for rank in report['ranks']:
    observations = []
    for observed in rank['observations']:
        item = {k: observed[k] for k in ('run','event_ref','operation','operator_tag_line','captured_source_line','function','unaligned_before','io')}
        item['source_file'] = 'deepspeed/runtime/zero/stage_1_and_2.py'
        observations.append(item)
    compact['ranks'].append({'rank': rank['rank'], 'observations': observations})
packets = {'trace': ''.join(parts), 'opguard': shared + json.dumps(compact, indent=2) + '\n'}
for arm, content in packets.items():
    (ROOT / f'demo/inputs/{arm}.txt').write_text(content)
(ROOT / 'demo/packets.js').write_text('// Generated by build_packets.py.\nexport const packets = ' + json.dumps(packets) + ';\n')
print({k: len(v.encode()) for k,v in packets.items()})
